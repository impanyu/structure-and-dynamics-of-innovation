"""Regenerate specialist/broad/mixed experiment configs. Specialists draw ONE
topic at RUN TIME from the k=50 pool (configs/topics-k50.yaml, generated from
data/stage1/topics_k50.json) via read/write_topics: "random" — assignment is
seeded, distinct within a run, and recorded in run_meta.json.
Run: uv run python scripts/gen_topic_configs.py"""
import json

import yaml

MASS = 800  # equal-mass regions: each topic scope = its 800 nearest corpus papers
topics = json.load(open("data/stage1/topics_k50.json"))
yaml.safe_dump({"mass": MASS, "topics": topics},
               open("configs/topics-k50.yaml", "w"), allow_unicode=True)


def spec_agent(aid, mass=MASS):
    # Specialist = READ-scoped only (user redefinition 2026-08-30): confined
    # to its topic for reading/citing, but writes freely (no content gate).
    return {"agent_id": aid, "policy": "llm",
            "read_topics": "random", "read_mass": mass}


def gen_agent(aid):
    return {"agent_id": aid, "policy": "llm"}


HEADER = ("# GENERATED by scripts/gen_topic_configs.py.\n"
          "# Specialists get ONE random topic from configs/topics-k50.yaml per run\n"
          "# (seeded, distinct within a run, recorded in run_meta.json).\n"
          "# Edit the generator, not this file.\n")


def write(path, run_id, agents, comment):
    cfg = {"extends": "../stage1.yaml",
           "run": {"run_id": run_id, "seed": 0, "total_steps": 400,
                   "agents": agents}}
    with open(path, "w") as f:
        f.write(HEADER + f"# {comment}\n")
        yaml.safe_dump(cfg, f, allow_unicode=True, sort_keys=False, width=100)


# CORE MATRIX (user redesign 2026-08-30): the specialization dial. C1 =
# generalists (the mass=infinity endpoint); C2-C6 = 10 read-scoped
# specialists with read_mass in {400, 800, 1600, 3200, 6400}. Same seed
# everywhere -> identical topic draws; only the radius varies. (Old C3
# broad-readers and C4 mixed-team conditions were withdrawn.)
CORE_MASSES = {"c2": 400, "c3": 800, "c4": 1600, "c5": 3200, "c6": 6400}
for cid, mass in CORE_MASSES.items():
    write(f"configs/experiments/core-mass-{mass}.yaml", f"core-mass-{mass}",
          [spec_agent(f"s{i}", mass) for i in range(10)],
          f"{cid.upper()} core: 10 specialists, each READS only its random topic "
          f"(read_mass={mass}); writes freely")
write("configs/experiments/supp-mixed-spec-heavy.yaml", "supp-mixed-spec-heavy",
      [spec_agent(f"s{i}") for i in range(7)] + [gen_agent(f"g{i}") for i in range(3)],
      "supplementary composition sweep: 7 specialists + 3 generalists")
write("configs/experiments/supp-mixed-gen-heavy.yaml", "supp-mixed-gen-heavy",
      [spec_agent(f"s{i}") for i in range(3)] + [gen_agent(f"g{i}") for i in range(7)],
      "supplementary composition sweep: 3 specialists + 7 generalists")
print("configs regenerated")
